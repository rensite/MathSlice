import { SHAPES } from './geometry.js';
import { edgePointId } from './points.js';

// Ratios are measured in the written direction, before canonical ID sorting.
const lesson = (shapeId, suffix, level, title, edges, sides, kind, hint, explanation) => {
  const midpoint = suffix === 'midpoints';
  const names = ['P','Q','R'];
  const instructions = edges.map(([from,to,t = .5], i) => midpoint
    ? `${names[i]} — середина ребра ${from}→${to}`
    : `${names[i]} на ребре ${from}→${to}: ${from}${names[i]}:${names[i]}${to} = ${t < .5 ? '1:2' : '2:1'} (от ${from} к ${to})`);
  return {
    id: `${shapeId}-edge-${suffix}`, shapeId, level, title,
    task: `${instructions.join('; ')}. Выберите эти три точки на рёбрах и постройте всё сечение плоскостью PQR, а не только треугольник PQR.`,
    target: edges.map(([from,to,t = .5]) => edgePointId(SHAPES[shapeId], from, to, t)),
    sides, kind, hint, explanation, pointMode: 'edges',
  };
};

